"""Writes the weights of a trained actor (actor.h, RLtools code export) as a plain C++ header for deployment.

python tools/export_policy.py <run>/actor.h <out.h>

The actor is the MLP of train_sac.cpp: 62 inputs, two hidden layers of 64 with ReLU, 8 outputs (the 4 action means,
then the 4 log standard deviations). At deployment the action is tanh(mean), as in the evaluation of train_sac.cpp.
The header defines fixed_wing::policy::{W0, b0, W1, b1, W2, b2} (row-major: W[out][in]) and evaluate().
"""
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text()
arrays = [[float.fromhex(v.strip().rstrip("f")) for v in body.split(",") if v.strip()]
          for body in re.findall(r"constexpr float memory\[\] = \{(.*?)\};", source, re.S)]
shapes = [(64, 62), (64,), (64, 64), (64,), (8, 64), (8,)]  # input, hidden and output layers: weights then biases
if [len(a) for a in arrays] != [s[0] * (s[1] if len(s) > 1 else 1) for s in shapes]:
    raise SystemExit(f"unexpected actor layout: {[len(a) for a in arrays]}")


def array(name, values, shape):
    dims = "".join(f"[{d}]" for d in shape)
    return f"    constexpr float {name}{dims} = {{{', '.join(repr(v) + 'f' for v in values)}}};\n"


names = ["W0", "b0", "W1", "b1", "W2", "b2"]
out = ["// generated by tools/export_policy.py from " + Path(sys.argv[1]).as_posix() + "\n#pragma once\n#include <cmath>\n\n",
       "namespace fixed_wing::policy{\n    constexpr int INPUT = 62, HIDDEN = 64, ACTIONS = 4;\n"]
for name, values, shape in zip(names, arrays, shapes):
    out.append(array(name, values, shape))
out.append("""
    // deterministic action of the trained actor: tanh of the action means, in [-1, 1]
    inline void evaluate(const float observation[INPUT], float action[ACTIONS]){
        float h0[HIDDEN], h1[HIDDEN];
        for(int i = 0; i < HIDDEN; i++){
            float x = b0[i];
            for(int j = 0; j < INPUT; j++) x += W0[i][j] * observation[j];
            h0[i] = x > 0 ? x : 0;
        }
        for(int i = 0; i < HIDDEN; i++){
            float x = b1[i];
            for(int j = 0; j < HIDDEN; j++) x += W1[i][j] * h0[j];
            h1[i] = x > 0 ? x : 0;
        }
        for(int i = 0; i < ACTIONS; i++){
            float x = b2[i];
            for(int j = 0; j < HIDDEN; j++) x += W2[i][j] * h1[j];
            action[i] = std::tanh(x);
        }
    }
}
""")
Path(sys.argv[2]).write_text("".join(out))
print("wrote", sys.argv[2])
